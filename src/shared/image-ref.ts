/**
 * Markdown 图片引用匹配(如 ![alt](./assets/imgs/x.png)),捕获组为完整引用路径。
 * 主进程孤儿图片清理(image-cleanup)与渲染端 PDF 导出(export-pdf)共用,
 * 保证两端对「什么算图片引用」的判定一致。
 *
 * alt 部分 `(?:\](?!\()[^\]]*)*` 容忍 `]` 出现在 alt 中(编辑器以 ![alt](path)
 * 插入且 alt 可被编辑含 `]`),清理端对这类引用失明会误删仍被引用的图片。
 * 每个被容忍的 `]` 不得紧跟 `(`(`](` 是 alt 真正结束、URL 开始的标志),
 * 否则贪婪的 alt 会吞并紧随其后的整条 `![...](...)` 引用,导致漏提取。
 */
export const IMAGE_REF_REGEX = /!\[[^\]]*(?:\](?!\()[^\]]*)*\]\(([^)]*\/assets\/[^)]+)\)/g
